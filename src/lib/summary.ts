import type { Snapshot } from './types';
import { transcriptHighlights } from './transcript';
import { duration } from './format';
export function summary(data: Snapshot) {
  const { meeting, events, members } = data;
  const lines = [
    `# ${meeting.title}`,
    '',
    `Started: ${new Date(meeting.created).toISOString()}`,
    `Participants: ${members
      .filter((m) => m.status === 'admitted')
      .map((m) => m.name)
      .join(', ')}`,
    '',
  ];
  const transcript = events
    .filter((e) => e.kind === 'transcript')
    .sort((a, b) => a.created - b.created || a.id - b.id);
  const line = (e: (typeof events)[number]) =>
    `- [${duration((e.created - meeting.created) / 1000)}] ${e.name}: ${e.payload.text}`;
  const highlights = transcriptHighlights(transcript);
  if (highlights.length) lines.push('## Discussion highlights', ...highlights.map(line), '');
  lines.push(
    '## Shared notes',
    [meeting.state.notes, meeting.state.liveNote?.text].filter(Boolean).join('\n\n') ||
      'No notes saved.',
  );
  if (meeting.state.bookmarks?.length) {
    lines.push('', '## Bookmarks');
    for (const mark of meeting.state.bookmarks) {
      lines.push(
        `- [${duration((mark.created - meeting.created) / 1000)}] ${mark.label} — ${mark.name}`,
      );
    }
  }
  const markers = events.filter((e) => e.kind === 'marker');
  if (markers.length) lines.push('', '## Feedback & moments');
  for (const e of markers)
    lines.push(
      `- [${duration((e.created - meeting.created) / 1000)}] ${e.name} · ${e.payload.kind}: ${e.payload.text}`,
    );
  if (meeting.state.actionItems?.length) lines.push('', '## Action items');
  for (const item of meeting.state.actionItems ?? [])
    lines.push(
      `- [${item.done ? 'x' : ' '}] ${item.title} — ${item.ownerName}${item.due ? ' · due ' + item.due : ''}`,
    );
  if (meeting.state.decisions?.length) lines.push('', '## Decision log');
  for (const decision of meeting.state.decisions ?? [])
    lines.push(
      `- ${decision.title} — ${decision.recordedBy} (${new Date(decision.created).toISOString().slice(0, 10)})`,
      ...(decision.reason ? ['  ' + decision.reason] : []),
    );
  if (meeting.state.polls.length) lines.push('', '## Polls');
  for (const p of meeting.state.polls) {
    lines.push(
      `### ${p.question}`,
      ...p.options.map(
        (o, i) => `- ${o}: ${Object.values(p.votes).filter((v) => v === i).length} votes`,
      ),
    );
  }
  const { url, task } = meeting.state.review;
  if (url || task) lines.push('', '## Product review', ...[url, task].filter(Boolean));
  const ratings = events.filter((e) => e.kind === 'rating');
  if (ratings.length) lines.push('', '## Meeting feedback');
  for (const e of ratings) lines.push(`- ${e.name}: ${e.payload.rating}/5 — ${e.payload.text}`);
  if (transcript.length) lines.push('', '## Speaker transcript', ...transcript.map(line));
  lines.push(
    '',
    '---',
    transcript.length
      ? 'Speech excerpts are automatically transcribed from opted-in microphones.'
      : 'Generated by Playground Meet from participant contributions. No AI processing was used to generate these notes.',
  );
  return lines.join('\n');
}
